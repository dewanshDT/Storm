#[test]
fn the_documented_delimiter_collision_still_exists_and_is_refused() {
    // Decision 60. The collision is not a curiosity — it is the reason both
    // fields are validated, and if a framing change ever removed it this
    // section would be describing a hazard it had silently outlived.
    let doc = vectors();
    let pairs = doc["delimiter_confusion"]["colliding_pairs"]
        .as_array()
        .expect("delimiter_confusion.colliding_pairs missing");
    assert!(!pairs.is_empty());
    for pair in pairs {
        let (a, b) = (&pair["a"], &pair["b"]);
        let ma = relay_auth_message(s(a, "server_id"), s(a, "nonce"));
        assert_eq!(
            ma,
            relay_auth_message(s(b, "server_id"), s(b, "nonce")),
            "the pair no longer collides"
        );
        assert_eq!(ma, s(pair, "shared_message_utf8").as_bytes());

        for side in [a, b] {
            let accepted = validate_server_id(s(side, "server_id")).is_ok()
                && validate_nonce(s(side, "nonce")).is_ok();
            assert!(
                !accepted,
                "a colliding pair passed validation — one signature would cover \
                 two different (server_id, nonce) readings"
            );
        }
    }
}

