#[test]
fn the_seeded_identity_is_the_key_the_vectors_were_generated_from() {
    // If this fails, every signature assertion below fails for an uninteresting
    // reason, so it is worth asserting separately.
    let doc = vectors();
    let identity = ServerIdentity::from_seed("srv_unused", SEED);
    assert_eq!(
        identity.public_key_b64(),
        s(&doc["keys"], "test_public_key_b64")
    );
}

#[test]
fn sign_relay_auth_reproduces_the_vector_signature_exactly() {
    let doc = vectors();
    let case = only_valid(&doc, "verify_relay_auth");
    let identity = ServerIdentity::from_seed(s(case, "server_id"), SEED);
    assert_eq!(
        identity.public_key_b64(),
        s(case, "public_key_b64"),
        "the vector was signed with a different key"
    );
    assert_eq!(
        identity
            .sign_relay_auth(s(case, "nonce"))
            .expect("the vector's nonce must be valid"),
        s(case, "signature_b64"),
        "sign_relay_auth no longer produces the bytes a relay will verify"
    );
}

#[test]
fn sign_challenge_reproduces_the_vector_signature_exactly() {
    let doc = vectors();
    let case = only_valid(&doc, "verify_client_challenge");
    let identity = ServerIdentity::from_seed(s(case, "server_id"), SEED);
    assert_eq!(identity.public_key_b64(), s(case, "public_key_b64"));
    assert_eq!(
        identity.sign_challenge(s(case, "nonce")),
        s(case, "signature_b64"),
        "sign_challenge no longer produces the bytes the client will verify"
    );
}

#[test]
fn the_two_domains_never_produce_the_same_signature() {
    // The property the prefixes exist for, asserted on real signatures rather
    // than inferred from the message builders: one signature must never prove
    // both "I may register at this relay" and "I am your server".
    let doc = vectors();
    let relay = only_valid(&doc, "verify_relay_auth");
    let challenge = only_valid(&doc, "verify_client_challenge");
    assert_eq!(
        s(relay, "server_id"),
        s(challenge, "server_id"),
        "the two positive vectors must share a server_id for this to mean anything"
    );
    assert_eq!(s(relay, "nonce"), s(challenge, "nonce"));
    assert_ne!(s(relay, "signature_b64"), s(challenge, "signature_b64"));
}

#[test]
fn sign_relay_auth_refuses_every_field_the_vectors_call_invalid() {
    // `sign_relay_auth` validates both fields itself rather than trusting its
    // caller, so the refusals are part of the signing contract and not only of
    // the validators.
    let doc = vectors();
    let good_nonce = s(only_valid(&doc, "verify_relay_auth"), "nonce");

    for case in cases(&doc, "validate_server_id") {
        if case["valid"].as_bool() == Some(false) {
            let identity = ServerIdentity::from_seed(s(case, "server_id"), SEED);
            assert!(
                identity.sign_relay_auth(good_nonce).is_err(),
                "signed for an invalid server_id (`{}`)",
                s(case, "name")
            );
        }
    }

    let identity = ServerIdentity::from_seed("srv_valid", SEED);
    for case in cases(&doc, "validate_nonce") {
        if case["valid"].as_bool() == Some(false) {
            assert!(
                identity.sign_relay_auth(s(case, "nonce")).is_err(),
                "signed an invalid nonce (`{}`)",
                s(case, "name")
            );
        }
    }
}
