import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../tool/ui_usage.dart';

void main() {
  final usage = scan(Directory('test/fixtures/ui_usage/lib'));

  String sites(String name) =>
      usage.components[name]!.map((s) => '${s.file}:${s.line}').join(' ');

  test('finds the public widget classes of the shared files', () {
    expect(usage.components.keys.toList(), [
      'Badge',
      'Button',
      'Chips',
      'Unused',
    ]);
  });

  test(
    'counts constructors, const, named, generic and interpolated code, in order',
    () {
      expect(
        sites('Button'),
        'agent/screen.dart:4 agent/screen.dart:5 agent/screen.dart:13',
      );
      expect(sites('Badge'), 'agent/screen.dart:6');
      expect(sites('Chips'), 'agent/screen.dart:7');
      expect(sites('Unused'), isEmpty);
    },
  );

  test('skips comments, strings and generated files', () {
    expect(usage.components['Button']!.map((s) => s.file).toSet(), {
      'agent/screen.dart',
    });
  });

  test('finds the one-off candidates', () {
    expect(
      usage.candidates
          .map((s) => '${s.file}:${s.line} ${s.kind!.name}')
          .toList(),
      [
        'agent/screen.dart:18 inkWell',
        'agent/screen.dart:19 gestureDetector',
        'agent/screen.dart:21 inkWell',
        'agent/screen.dart:23 boxDecoration',
        'agent/screen.dart:28 boxDecoration',
      ],
    );
  });

  test('renders a stable file', () {
    expect(render(usage), '''
// Generated by tool/ui_usage.dart; do not edit.
import 'usage.dart';

const componentUsage = <String, List<UsageSite>>{
  'Badge': [
    UsageSite('agent/screen.dart', 6),
  ],
  'Button': [
    UsageSite('agent/screen.dart', 4),
    UsageSite('agent/screen.dart', 5),
    UsageSite('agent/screen.dart', 13),
  ],
  'Chips': [
    UsageSite('agent/screen.dart', 7),
  ],
  'Unused': <UsageSite>[],
};

const oneOffCandidates = <CandidateSite>[
  CandidateSite('agent/screen.dart', 18, CandidateKind.inkWell),
  CandidateSite('agent/screen.dart', 19, CandidateKind.gestureDetector),
  CandidateSite('agent/screen.dart', 21, CandidateKind.inkWell),
  CandidateSite('agent/screen.dart', 23, CandidateKind.boxDecoration),
  CandidateSite('agent/screen.dart', 28, CandidateKind.boxDecoration),
];
''');
  });
}
