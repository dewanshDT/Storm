//! The fixture contract: the server identities a relay under test must
//! allowlist, and the shortened timers and limits it must be started with.
//!
//! Both live in `fixtures/` as files rather than as constants here, because a
//! relay in another language (the Worker) reads the same files.

use std::collections::HashMap;
use std::path::Path;
use std::time::Duration;

use anyhow::{Context, Result, anyhow, bail};
use data_encoding::BASE64URL_NOPAD;
use ed25519_dalek::{Signer, SigningKey};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

/// How many allowlisted identities `gen-fixtures` writes. Each test takes its
/// own, so no test inherits a registration or a drain timer from another.
pub const SERVER_COUNT: usize = 48;

pub const UNLISTED_SERVER_ID: &str = "srv_conf_unlisted";

/// Seeds are derived, not random, so `gen-fixtures` is reproducible and the
/// committed files can be checked against it.
const SEED_DOMAIN: &str = "storm-relay-conformance:v1:";

#[derive(Clone)]
pub struct Identity {
    pub server_id: String,
    pub key: SigningKey,
}

impl Identity {
    pub fn pubkey_b64(&self) -> String {
        BASE64URL_NOPAD.encode(self.key.verifying_key().as_bytes())
    }

    pub fn sign(&self, message: &str) -> String {
        BASE64URL_NOPAD.encode(&self.key.sign(message.as_bytes()).to_bytes())
    }

    /// `storm-relay-auth:v1:<server_id>:<nonce>` (§4), spelled out here rather
    /// than borrowed from any implementation under test.
    pub fn relay_auth(&self, nonce: &str) -> String {
        self.sign(&format!("storm-relay-auth:v1:{}:{nonce}", self.server_id))
    }

    pub fn with_id(&self, server_id: &str) -> Self {
        Self {
            server_id: server_id.to_string(),
            key: self.key.clone(),
        }
    }
}

fn derived(name: &str) -> SigningKey {
    let seed: [u8; 32] = Sha256::digest(format!("{SEED_DOMAIN}{name}").as_bytes()).into();
    SigningKey::from_bytes(&seed)
}

fn server_id(index: usize) -> String {
    format!("srv_conf_{index:02}")
}

pub struct Fixtures {
    pub servers: Vec<Identity>,
    /// A key on no allowlist line.
    pub intruder: SigningKey,
}

impl Fixtures {
    pub fn load(dir: &Path) -> Result<Self> {
        let path = dir.join("servers.json");
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        let doc: Value = serde_json::from_str(&text)?;
        let key = |entry: &Value| -> Result<SigningKey> {
            let seed = entry["seed_b64"]
                .as_str()
                .ok_or_else(|| anyhow!("seed_b64 missing in {entry}"))?;
            let bytes: [u8; 32] = BASE64URL_NOPAD
                .decode(seed.as_bytes())?
                .try_into()
                .map_err(|_| anyhow!("seed is not 32 bytes"))?;
            let key = SigningKey::from_bytes(&bytes);
            let expected = BASE64URL_NOPAD.encode(key.verifying_key().as_bytes());
            if entry["pubkey_b64"] != expected.as_str() {
                bail!("pubkey_b64 does not match seed_b64 in {entry}");
            }
            Ok(key)
        };
        let servers = doc["servers"]
            .as_array()
            .ok_or_else(|| anyhow!("servers missing"))?
            .iter()
            .map(|entry| {
                Ok(Identity {
                    server_id: entry["server_id"]
                        .as_str()
                        .ok_or_else(|| anyhow!("server_id missing"))?
                        .to_string(),
                    key: key(entry)?,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        if servers.is_empty() {
            bail!("no servers in {}", path.display());
        }
        Ok(Self {
            servers,
            intruder: key(&doc["intruder"])?,
        })
    }
}

fn entry(server_id: Option<&str>, key: &SigningKey) -> Value {
    let mut value = json!({
        "seed_b64": BASE64URL_NOPAD.encode(key.as_bytes()),
        "pubkey_b64": BASE64URL_NOPAD.encode(key.verifying_key().as_bytes()),
    });
    if let Some(id) = server_id {
        value["server_id"] = json!(id);
    }
    value
}

/// `servers.json` and `allowlist`, exactly as committed.
pub fn generate() -> (String, String) {
    let mut servers = Vec::new();
    let mut allowlist = String::from(
        "# The relay conformance suite's allowlist (tools/relay-conformance).\n\
         # storm-relay format: <server_id> <pubkey>. Generated by\n\
         # `relay-conformance gen-fixtures`; servers.json holds the private seeds.\n\
         # Test keys only: never put one on a relay that serves real servers.\n",
    );
    for index in 0..SERVER_COUNT {
        let id = server_id(index);
        let key = derived(&id);
        allowlist.push_str(&format!(
            "{id} {}\n",
            BASE64URL_NOPAD.encode(key.verifying_key().as_bytes())
        ));
        servers.push(entry(Some(&id), &key));
    }
    let doc = json!({
        "about": "Fixed server identities for the SRP v1 relay conformance suite. \
                  Every server_id here is on fixtures/allowlist with its pubkey; \
                  `intruder` is a key on no line, and `unlisted_server_id` is an id \
                  on no line. Test keys only: the private seeds are public.",
        "derivation": "seed = SHA-256(\"storm-relay-conformance:v1:\" + name), where name \
                       is the server_id or \"intruder\"; Ed25519 (RFC 8032); every \
                       binary field base64url without padding",
        "unlisted_server_id": UNLISTED_SERVER_ID,
        "intruder": entry(None, &derived("intruder")),
        "servers": servers,
    });
    let mut json = serde_json::to_string_pretty(&doc).expect("a json value serializes");
    json.push('\n');
    (json, allowlist)
}

pub fn write(dir: &Path) -> Result<()> {
    let (servers, allowlist) = generate();
    std::fs::create_dir_all(dir)?;
    std::fs::write(dir.join("servers.json"), servers)?;
    std::fs::write(dir.join("allowlist"), allowlist)?;
    Ok(())
}

/// The relay's timers and limits, read from `fixtures/relay.env`: the values
/// the relay under test was started with, so the suite knows what to expect.
#[derive(Debug, Clone)]
pub struct Knobs {
    pub challenge_ttl: Duration,
    pub hello_wait: Duration,
    pub stream_ack_timeout: Duration,
    pub heartbeat_deadline: Duration,
    pub supersession_drain: Duration,
    pub hello_rate_limit: usize,
    pub hello_rate_window: Duration,
    pub max_in_flight_streams: usize,
    pub max_total_streams: usize,
    pub max_client_buffer_bytes: usize,
}

impl Knobs {
    pub fn load(path: &Path) -> Result<Self> {
        let text =
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        Self::parse(&text).with_context(|| format!("parsing {}", path.display()))
    }

    pub fn parse(text: &str) -> Result<Self> {
        let mut vars = HashMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (key, value) = line
                .split_once('=')
                .ok_or_else(|| anyhow!("expected KEY=VALUE, got {line}"))?;
            vars.insert(key.trim().to_string(), value.trim().to_string());
        }
        let number = |key: &str| -> Result<u64> {
            vars.get(key)
                .ok_or_else(|| anyhow!("{key} is not set"))?
                .parse()
                .with_context(|| format!("{key} is not a number"))
        };
        let ms = |key: &str| number(key).map(Duration::from_millis);
        Ok(Self {
            challenge_ttl: ms("STORM_RELAY_CHALLENGE_TTL_MS")?,
            hello_wait: ms("STORM_RELAY_HELLO_WAIT_MS")?,
            stream_ack_timeout: ms("STORM_RELAY_STREAM_ACK_TIMEOUT_MS")?,
            heartbeat_deadline: ms("STORM_RELAY_HEARTBEAT_DEADLINE_MS")?,
            supersession_drain: ms("STORM_RELAY_SUPERSESSION_DRAIN_MS")?,
            hello_rate_limit: number("STORM_RELAY_HELLO_RATE_LIMIT")? as usize,
            hello_rate_window: ms("STORM_RELAY_HELLO_RATE_WINDOW_MS")?,
            max_in_flight_streams: number("STORM_RELAY_MAX_IN_FLIGHT_STREAMS")? as usize,
            max_total_streams: number("STORM_RELAY_MAX_TOTAL_STREAMS")? as usize,
            max_client_buffer_bytes: number("STORM_RELAY_MAX_CLIENT_BUFFER_BYTES")? as usize,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dir() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures")
    }

    #[test]
    fn the_committed_fixtures_are_what_gen_fixtures_writes() {
        let (servers, allowlist) = generate();
        assert_eq!(
            std::fs::read_to_string(dir().join("servers.json")).unwrap(),
            servers,
            "fixtures/servers.json drifted; run `relay-conformance gen-fixtures fixtures`"
        );
        assert_eq!(
            std::fs::read_to_string(dir().join("allowlist")).unwrap(),
            allowlist,
            "fixtures/allowlist drifted"
        );
    }

    #[test]
    fn the_committed_fixtures_load() {
        let fixtures = Fixtures::load(&dir()).unwrap();
        assert_eq!(fixtures.servers.len(), SERVER_COUNT);
        Knobs::load(&dir().join("relay.env")).unwrap();
    }
}
